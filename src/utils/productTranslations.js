/**
 * Returns localized product fields based on selected language key
 */
export function getLocalizedProduct(product, langKey = 'ar') {
  if (!product) return product;
  if (!langKey || langKey === 'ar') return product;

  const prodTrans = PRODUCT_TRANSLATIONS[product.id]?.[langKey];

  if (prodTrans) {
    return {
      ...product,
      title: prodTrans.title || product.title,
      description: prodTrans.description || product.description,
      deliveryDays: prodTrans.deliveryDays || product.deliveryDays,
      colors: prodTrans.colors || product.colors,
      specs: prodTrans.specs || product.specs
    };
  }

  // Dynamic automatic Chinese (zh) localization engine fallback
  if (langKey === 'zh') {
    let zhDelivery = product.deliveryDays;
    if (typeof zhDelivery === 'string') {
      zhDelivery = zhDelivery
        .replace(/شحن/g, '')
        .replace(/أيام/g, '天')
        .replace(/يوم/g, '天')
        .trim() + ' 官方直邮包邮';
    }

    let zhTitle = product.title;
    // Map common keywords to clean Chinese
    if (zhTitle.includes('سماعات')) zhTitle = zhTitle.replace('سماعات', '无线耳机');
    if (zhTitle.includes('ساعة')) zhTitle = zhTitle.replace('ساعة', '智能手表');
    if (zhTitle.includes('شاحن')) zhTitle = zhTitle.replace('شاحن', '快充充电器');
    if (zhTitle.includes('باور بنك')) zhTitle = zhTitle.replace('باور بنك', '移动电源');
    if (zhTitle.includes('بروجيكتور')) zhTitle = zhTitle.replace('بروجيكتور', '智能投影仪');
    if (zhTitle.includes('كاميرا')) zhTitle = zhTitle.replace('كاميرا', '4K高清运动相机');
    if (zhTitle.includes('درون')) zhTitle = zhTitle.replace('درون', '高清航拍无人机');
    if (zhTitle.includes('مكنسة')) zhTitle = zhTitle.replace('مكنسة', '智能扫地机器人');
    if (zhTitle.includes('كيبورد')) zhTitle = zhTitle.replace('كيبورد', 'RGB机械键盘');

    return {
      ...product,
      title: zhTitle,
      deliveryDays: zhDelivery
    };
  }

  // Fallback to English translation if available, or product
  const fallbackEn = PRODUCT_TRANSLATIONS[product.id]?.en;
  if (fallbackEn) {
    return {
      ...product,
      title: fallbackEn.title || product.title,
      description: fallbackEn.description || product.description,
      deliveryDays: fallbackEn.deliveryDays || product.deliveryDays,
      colors: fallbackEn.colors || product.colors,
      specs: fallbackEn.specs || product.specs
    };
  }

  return product;
}
